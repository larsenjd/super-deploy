// Regenerates src/sql-analysis/pg-catalog-names.ts: the names PostgreSQL 18
// has in pg_catalog, so ordering can tell a built-in reference from an
// unknown one without a database (SQL analysis is database-free), and
// destructive analysis can tell a volatile default (a table rewrite) from a
// stable one.
//
// Run after a PostgreSQL major or embedded-postgres upgrade:
//   node scripts/generate-pg-catalog-names.ts
import { mkdtemp, rm, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import pg from "pg";
import { embeddedPostgres } from "../src/adapters/embedded-postgres.ts";

const output = join(
  import.meta.dirname,
  "..",
  "src",
  "sql-analysis",
  "pg-catalog-names.ts",
);

const root = await mkdtemp(join(tmpdir(), "super-deploy-catalog-names-"));
const server = embeddedPostgres({ dataDir: join(root, "data") });
try {
  const client = new pg.Client({
    connectionString: await server.connectionString(),
  });
  client.on("error", () => {});
  await client.connect();
  const names = async (sql: string): Promise<string[]> =>
    (await client.query<{ name: string }>(sql)).rows
      .map((row) => row.name)
      .sort((a, b) => (a < b ? -1 : a > b ? 1 : 0));
  const version = (
    await client.query<{ server_version: string }>("SHOW server_version")
  ).rows[0]?.server_version;
  const functions = await names(
    "SELECT DISTINCT proname AS name FROM pg_proc WHERE pronamespace = 'pg_catalog'::regnamespace",
  );
  // A name counts as volatile when any overload is: PostgreSQL resolves
  // overloads by argument types, which the SQL analysis cannot see.
  const volatileFunctions = await names(
    "SELECT DISTINCT proname AS name FROM pg_proc WHERE pronamespace = 'pg_catalog'::regnamespace AND provolatile = 'v'",
  );
  const types = await names(
    "SELECT typname AS name FROM pg_type WHERE typnamespace = 'pg_catalog'::regnamespace",
  );
  const relations = await names(
    "SELECT relname AS name FROM pg_class WHERE relnamespace = 'pg_catalog'::regnamespace",
  );
  await client.end();

  const list = (values: string[]) =>
    `[${values.map((v) => JSON.stringify(v)).join(",")}]`;
  await writeFile(
    output,
    `// Generated by scripts/generate-pg-catalog-names.ts from PostgreSQL ${version}. Do not edit.
// biome-ignore-all format: generated
export const pgCatalogFunctions: ReadonlySet<string> = new Set(${list(functions)});
export const pgCatalogVolatileFunctions: ReadonlySet<string> = new Set(${list(volatileFunctions)});
export const pgCatalogTypes: ReadonlySet<string> = new Set(${list(types)});
export const pgCatalogRelations: ReadonlySet<string> = new Set(${list(relations)});
`,
  );
  console.log(
    `PostgreSQL ${version}: ${functions.length} functions (${volatileFunctions.length} volatile), ${types.length} types, ${relations.length} relations`,
  );
} finally {
  await server.stop();
  await rm(root, { recursive: true, force: true });
}
