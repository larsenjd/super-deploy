// Regenerates src/sql-analysis/supported-extensions.ts: the supported
// extensions (ADR-0009), each with the versions it can be installed at and
// what it provides at each one. It is the single source for which extensions
// and versions the tool knows: the config validator reads the versions, and
// ordering resolves an extension's types, functions, operators and operator
// classes against the objects.
//
// For each name in `supportedExtensionNames` below, the versions are the ones
// embedded-postgres offers (`pg_available_extension_versions`). Each version
// is installed with `CREATE EXTENSION ... VERSION` into a fresh database from
// template0, and its members (pg_depend deptype `e`) are read: types,
// functions with their argument types, operators, operator classes and
// operator families. Everything is sorted, so a run on the same server gives
// byte-identical output (test/integration/supported-extensions.test.ts checks
// the committed file against a fresh run).
//
// Run after an embedded-postgres upgrade, or after changing the set:
//   node scripts/generate-supported-extensions.ts
// Then check a real target offers the same: scripts/check-supported-extensions.ts.
import { mkdtemp, rm, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import pg from "pg";
import { embeddedPostgres } from "../src/adapters/embedded-postgres.ts";

/**
 * The supported set: trusted, offered by Aurora PostgreSQL 18.4, loadable on
 * every embedded-postgres platform, and transaction-safe
 * (.scratch/extensions/research/supported-extensions.md §1).
 */
export const supportedExtensionNames = [
  "btree_gin",
  "btree_gist",
  "citext",
  "cube",
  "dict_int",
  "fuzzystrmatch",
  "hstore",
  "intarray",
  "isn",
  "ltree",
  "pg_trgm",
  "pgcrypto",
  "tablefunc",
  "tsm_system_rows",
  "tsm_system_time",
  "unaccent",
  "uuid-ossp",
] as const;

const output = join(
  import.meta.dirname,
  "..",
  "src",
  "sql-analysis",
  "supported-extensions.ts",
);

interface Objects {
  types: string[];
  functions: { name: string; arguments: string[] }[];
  operators: { name: string; left: string | null; right: string }[];
  operatorClasses: { name: string; method: string }[];
  operatorFamilies: { name: string; method: string }[];
}

/** The source of supported-extensions.ts, read from the server at `connectionString` (a superuser). */
export async function supportedExtensionsSource(
  connectionString: string,
): Promise<string> {
  const admin = await connect(connectionString);
  const versions = new Map<string, string[]>();
  let serverVersion: string;
  try {
    serverVersion = (
      await admin.query<{ server_version: string }>("SHOW server_version")
    ).rows[0]?.server_version as string;
    const { rows } = await admin.query<{ name: string; version: string }>(
      "SELECT name, version FROM pg_available_extension_versions WHERE name = ANY($1)",
      [supportedExtensionNames],
    );
    for (const name of supportedExtensionNames) {
      const offered = rows
        .filter((row) => row.name === name)
        .map((row) => row.version)
        .sort(compareVersions);
      if (offered.length === 0) {
        throw new Error(`The server offers no version of ${name}`);
      }
      versions.set(name, offered);
    }
  } finally {
    await admin.end();
  }

  const objects: string[] = [];
  for (const [name, offered] of versions) {
    const lines: string[] = [];
    for (const version of offered) {
      const found = await installedObjects(connectionString, name, version);
      lines.push(`${JSON.stringify(version)}: ${JSON.stringify(found)},`);
    }
    objects.push(`${JSON.stringify(name)}: {\n${lines.join("\n")}\n},`);
  }
  const versionLines = [...versions].map(
    ([name, offered]) => `${JSON.stringify(name)}: ${JSON.stringify(offered)},`,
  );

  return `// Generated by scripts/generate-supported-extensions.ts from PostgreSQL ${serverVersion}. Do not edit.
// biome-ignore-all format: generated

/** Each supported extension (ADR-0009) and the versions it can be installed at, oldest first. */
export const supportedExtensionVersions = {
${versionLines.join("\n")}
} as const;

/** The name of a supported extension. */
export type SupportedExtension = keyof typeof supportedExtensionVersions;

/** What an extension provides at one version: its members, named as SQL writes them unqualified. */
export interface ExtensionObjects {
  readonly types: readonly string[];
  /** Functions, aggregates and procedures, with their input argument types. */
  readonly functions: readonly { readonly name: string; readonly arguments: readonly string[] }[];
  /** \`left\` is null for a prefix operator. */
  readonly operators: readonly { readonly name: string; readonly left: string | null; readonly right: string }[];
  /** \`method\` is the index access method, e.g. \`gin\`. */
  readonly operatorClasses: readonly { readonly name: string; readonly method: string }[];
  readonly operatorFamilies: readonly { readonly name: string; readonly method: string }[];
}

/** What each supported extension provides at each of its versions. */
export const supportedExtensionObjects: { readonly [Name in SupportedExtension]: Readonly<Record<string, ExtensionObjects>> } = {
${objects.join("\n")}
};
`;
}

async function installedObjects(
  connectionString: string,
  name: string,
  version: string,
): Promise<Objects> {
  const admin = await connect(connectionString);
  const database = `super_deploy_extension_${process.pid}`;
  try {
    await admin.query(`DROP DATABASE IF EXISTS ${database}`);
    await admin.query(`CREATE DATABASE ${database} TEMPLATE template0`);
    const url = new URL(connectionString);
    url.pathname = `/${database}`;
    const client = await connect(url.href);
    try {
      await client.query(
        `CREATE EXTENSION ${client.escapeIdentifier(name)} VERSION ${client.escapeLiteral(version)}`,
      );
      return await members(client, name);
    } finally {
      await client.end();
    }
  } finally {
    await admin.query(`DROP DATABASE IF EXISTS ${database}`);
    await admin.end();
  }
}

// Every query joins pg_depend for the extension's members (deptype 'e').
const member = (catalog: string, alias: string) =>
  `JOIN pg_depend d ON d.classid = '${catalog}'::regclass AND d.objid = ${alias}.oid AND d.deptype = 'e'
   JOIN pg_extension e ON d.refclassid = 'pg_extension'::regclass AND d.refobjid = e.oid AND e.extname = $1`;

async function members(client: pg.Client, name: string): Promise<Objects> {
  const rows = async <Row extends pg.QueryResultRow>(sql: string) =>
    (await client.query<Row>(sql, [name])).rows;
  const types = (
    await rows<{ name: string }>(
      `SELECT t.typname AS name FROM pg_type t ${member("pg_type", "t")}`,
    )
  ).map((row) => row.name);
  const functions = await rows<{ name: string; arguments: string[] }>(
    `SELECT p.proname AS name,
       ARRAY(SELECT format_type(a.type, NULL) FROM unnest(p.proargtypes::oid[]) WITH ORDINALITY a(type, n) ORDER BY a.n) AS arguments
     FROM pg_proc p ${member("pg_proc", "p")}`,
  );
  const operators = await rows<{
    name: string;
    left: string | null;
    right: string;
  }>(
    `SELECT o.oprname AS name,
       CASE WHEN o.oprleft = 0 THEN NULL ELSE format_type(o.oprleft, NULL) END AS left,
       format_type(o.oprright, NULL) AS right
     FROM pg_operator o ${member("pg_operator", "o")}`,
  );
  const operatorClasses = await rows<{ name: string; method: string }>(
    `SELECT c.opcname AS name, am.amname AS method
     FROM pg_opclass c JOIN pg_am am ON am.oid = c.opcmethod ${member("pg_opclass", "c")}`,
  );
  const operatorFamilies = await rows<{ name: string; method: string }>(
    `SELECT f.opfname AS name, am.amname AS method
     FROM pg_opfamily f JOIN pg_am am ON am.oid = f.opfmethod ${member("pg_opfamily", "f")}`,
  );
  return {
    types: types.sort(compareText),
    functions: functions.sort(
      (a, b) =>
        compareText(a.name, b.name) ||
        compareText(a.arguments.join(","), b.arguments.join(",")),
    ),
    operators: operators.sort(
      (a, b) =>
        compareText(a.name, b.name) ||
        compareText(a.left ?? "", b.left ?? "") ||
        compareText(a.right, b.right),
    ),
    operatorClasses: operatorClasses.sort(byNameAndMethod),
    operatorFamilies: operatorFamilies.sort(byNameAndMethod),
  };
}

async function connect(connectionString: string): Promise<pg.Client> {
  const client = new pg.Client({ connectionString });
  client.on("error", () => {});
  await client.connect();
  return client;
}

function byNameAndMethod(
  a: { name: string; method: string },
  b: { name: string; method: string },
): number {
  return compareText(a.name, b.name) || compareText(a.method, b.method);
}

/** Code-unit order, never the locale's, so output is the same everywhere. */
function compareText(a: string, b: string): number {
  return a < b ? -1 : a > b ? 1 : 0;
}

/** Dotted versions by number: 1.9 before 1.10. */
export function compareVersions(a: string, b: string): number {
  const left = a.split(".").map(Number);
  const right = b.split(".").map(Number);
  for (let i = 0; i < Math.max(left.length, right.length); i++) {
    const difference = (left[i] ?? 0) - (right[i] ?? 0);
    if (difference !== 0) {
      return difference;
    }
  }
  return compareText(a, b);
}

if (import.meta.main) {
  const root = await mkdtemp(join(tmpdir(), "super-deploy-extensions-"));
  const server = embeddedPostgres({ dataDir: join(root, "data") });
  try {
    const source = await supportedExtensionsSource(
      await server.connectionString(),
    );
    await writeFile(output, source);
    console.log(`Wrote ${output}`);
  } finally {
    await server.stop();
    await rm(root, { recursive: true, force: true });
  }
}
