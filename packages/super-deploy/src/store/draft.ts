// The one draft: draft/draft.json holds its name (editable), the hash of
// the desired schema it was generated from (written by `draft`, used by
// `validate` to warn about undrafted changes) and the hash of the schema
// change `draft` wrote (so a rehearsal mismatch can name a hand edit; drafts
// written before it existed have none, and count as not edited);
// draft/schema-change.sql is the generated schema change, and
// draft/schema-change.generated.sql a copy of it as generated, so a hand
// edit is warned about and recorded (store/hand-edit.ts).
//
// A Recovery draft (created by `recovery --migration N`) has
// `"recoveryOf": N` in draft.json and the name of migration N; its
// schema-change.sql is a copy of migration N's, never regenerated, and its
// scripts and seed data become the next Recovery of migration N at finalize.
// The copy's header comment says so (recoverySchemaChange) instead of the
// generated one's "run draft again"; its statements are migration N's,
// unchanged, and the migration's own hashed file is never touched.
//
// A draft holds only draftFileNames, and a Recovery draft only
// recoveryDraftFileNames: its metadata, its copy of the schema change and the
// files a Recovery replaces. Anything else in its folder (a misnamed script
// such as `post-migrate.sql`, notes, or a Recovery draft's
// schema-change.generated.sql) never runs. `draft`, `rehearse` and `validate`
// warn about each one (unknownDraftFiles) and carry on: the maintainer chose a
// warning over a refusal while the draft is being written (QA 44). `draft` and
// `rehearse` report them through `onUnknownFile` before any check or rehearsal:
// a misnamed backfill is often why the rehearsal then fails. `finalize` refuses
// the first one (UnknownDraftFileError, refuseUnknownDraftFiles) before
// anything else, since a finalized migration or Recovery can't hold it
// (store/integrity.ts).

import { mkdir, readFile, writeFile } from "node:fs/promises";
import { join } from "node:path";
import { joined, SuperDeployError } from "../errors.ts";
import { isSqlFile } from "./desired-schema.ts";
import { normaliseDraftName } from "./draft-name.ts";
import { normaliseLineEndings } from "./hashing.ts";
import { type ProjectPaths, projectRelative } from "./layout.ts";
import {
  type FinalizedFolderKind,
  type FinalizedMigration,
  listFiles,
  postMigrationFileName,
  preMigrationFileName,
  readIfPresent,
  recoveryFileNames,
  schemaChangeFileName,
  seedDataFileName,
} from "./migrations.ts";

/** The header comment `draft` writes at the top of the schema change. */
export const schemaChangeHeader = [
  "-- Schema change generated by super-deploy draft. Do not edit: change the",
  "-- desired schema (or the pre-migration script) and run draft again.",
].join("\n");

/**
 * A Recovery draft's schema-change.sql: migration `folder`'s schema change
 * `original`, with a header saying it is that migration's and is never
 * regenerated in place of the generated header (or before the file, when it
 * has no generated header). Line endings are normalised to LF.
 */
export function recoverySchemaChange(original: string, folder: string): string {
  const header = [
    `-- Schema change of migration ${folder}, which this Recovery runs unchanged.`,
    "-- Do not edit, and draft never regenerates it: change the Recovery's",
    "-- pre-migration.sql, post-migration.sql and seed-data.sql instead.",
  ].join("\n");
  const text = normaliseLineEndings(original);
  return text.startsWith(`${schemaChangeHeader}\n`)
    ? `${header}${text.slice(schemaChangeHeader.length)}`
    : `${header}\n\n${text}`;
}

/** Writes `migration`'s schema change into a Recovery draft of it (recoverySchemaChange). */
export async function writeRecoverySchemaChange(
  paths: ProjectPaths,
  migration: FinalizedMigration,
): Promise<void> {
  const original = await readFile(
    join(migration.path, schemaChangeFileName),
    "utf8",
  );
  await writeFile(
    paths.draftSchemaChange,
    recoverySchemaChange(original, migration.folder),
  );
}

/** The draft's own metadata file; never copied into the finalized migration. */
export const draftMetadataFileName = "draft.json";

/**
 * The schema change as `draft` generated it, kept beside the draft so a hand
 * edit of schema-change.sql can be told and shown (store/hand-edit.ts).
 * Never run, and never copied into the finalized migration.
 */
export const generatedSchemaChangeFileName = "schema-change.generated.sql";

/**
 * Every file a draft may hold: its metadata, then its SQL in the order it
 * runs, with the generated copy of the schema change beside it.
 */
export const draftFileNames: readonly string[] = [
  draftMetadataFileName,
  seedDataFileName,
  preMigrationFileName,
  schemaChangeFileName,
  generatedSchemaChangeFileName,
  postMigrationFileName,
];

/**
 * Every file a Recovery draft may hold, in draftFileNames' order: its
 * metadata, its copy of the schema change, and the files a Recovery replaces.
 * It has no generated copy: its schema change is never generated.
 */
const recoveryDraftFileNames: readonly string[] = draftFileNames.filter(
  (name) =>
    name === draftMetadataFileName ||
    name === schemaChangeFileName ||
    recoveryFileNames.includes(name),
);

/** What `draft` finalizes as: a migration, or for a Recovery draft a Recovery. */
function finalizedAs(draft: DraftMetadata | undefined): FinalizedFolderKind {
  return draft?.recoveryOf === undefined ? "migration" : "Recovery";
}

/** A file in the draft folder that the draft doesn't hold (draftFileNames, or recoveryDraftFileNames). */
export interface UnknownDraftFile {
  /** Project-relative path. */
  readonly file: string;
  /** Names the file and the files a draft holds; for a `.sql` file, says it will not run. */
  readonly message: string;
}

export interface UnknownDraftFileOptions {
  /**
   * Called with each file in the draft folder that a draft doesn't hold,
   * before the draft is checked or rehearsed, so it is reported even when
   * the command then fails: such a file never runs.
   */
  onUnknownFile?: ((file: UnknownDraftFile) => void) | undefined;
}

/** Calls `onUnknownFile` with each of unknownDraftFiles. */
export async function reportUnknownDraftFiles(
  root: string,
  paths: ProjectPaths,
  draft: DraftMetadata | undefined,
  options: UnknownDraftFileOptions,
): Promise<void> {
  if (options.onUnknownFile === undefined) {
    return;
  }
  for (const file of await unknownDraftFiles(root, paths, draft)) {
    options.onUnknownFile(file);
  }
}

/**
 * The files under the draft folder that `draft` (its metadata, if it has
 * any) doesn't hold; none without a draft folder.
 */
export async function unknownDraftFiles(
  root: string,
  paths: ProjectPaths,
  draft: DraftMetadata | undefined,
): Promise<UnknownDraftFile[]> {
  const [names, kind] =
    finalizedAs(draft) === "Recovery"
      ? [recoveryDraftFileNames, "a Recovery draft"]
      : [draftFileNames, "a draft"];
  const holds = `${kind} holds ${joined(names)}`;
  return (await listFiles(paths.draft))
    .filter((path) => !names.includes(path))
    .map((path) => {
      const file = projectRelative(root, join(paths.draft, path));
      const runs = isSqlFile(path) ? ", so it will not run" : "";
      return {
        file,
        message: `${file} is not one of ${kind}'s files${runs} (${holds})`,
      };
    });
}

/** UnknownDraftFileError for the first of unknownDraftFiles, if any. */
export async function refuseUnknownDraftFiles(
  root: string,
  paths: ProjectPaths,
  draft: DraftMetadata | undefined,
): Promise<void> {
  const [unknown] = await unknownDraftFiles(root, paths, draft);
  if (unknown !== undefined) {
    throw new UnknownDraftFileError(unknown, finalizedAs(draft));
  }
}

export interface DraftMetadata {
  readonly name: string;
  /** store/hashing.ts desiredSchemaHash() of the desired schema `draft` last generated from. */
  readonly desiredSchemaHash?: string | undefined;
  /** For a Recovery draft: the number of the migration it recovers. */
  readonly recoveryOf?: number | undefined;
}

/** Reads draft.json; errors name it relative to the project `root`. */
export async function readDraft(
  root: string,
  paths: ProjectPaths,
): Promise<DraftMetadata | undefined> {
  const file = projectRelative(root, paths.draftMetadata);
  const text = await readIfPresent(paths.draftMetadata);
  if (text === undefined) {
    return undefined;
  }
  let parsed: unknown;
  try {
    parsed = JSON.parse(text);
  } catch (error) {
    throw new InvalidDraftError(
      file,
      `is not valid JSON (${(error as Error).message})`,
      { cause: error },
    );
  }
  if (
    typeof parsed !== "object" ||
    parsed === null ||
    !("name" in parsed) ||
    typeof parsed.name !== "string"
  ) {
    throw new InvalidDraftError(file, 'has no "name"');
  }
  const hash =
    "desiredSchemaHash" in parsed &&
    typeof parsed.desiredSchemaHash === "string"
      ? parsed.desiredSchemaHash
      : undefined;
  const recoveryOf = "recoveryOf" in parsed ? parsed.recoveryOf : undefined;
  if (
    recoveryOf !== undefined &&
    !(
      typeof recoveryOf === "number" &&
      Number.isInteger(recoveryOf) &&
      recoveryOf > 0
    )
  ) {
    throw new InvalidDraftError(
      file,
      'has a "recoveryOf" that is not a migration number',
    );
  }
  return {
    name: normaliseDraftName(parsed.name),
    desiredSchemaHash: hash,
    ...(recoveryOf === undefined ? {} : { recoveryOf }),
  };
}

/**
 * Writes draft.json, a copy of the generated schema change `generated`
 * (generatedSchemaChangeFileName) and the schema change `schemaChange`:
 * `generated` itself unless it is restored with a hand edit (unfinalize).
 */
export async function writeDraft(
  paths: ProjectPaths,
  metadata: DraftMetadata,
  generated: string,
  schemaChange: string = generated,
): Promise<void> {
  await writeDraftMetadata(paths, metadata);
  await writeFile(join(paths.draft, generatedSchemaChangeFileName), generated);
  await writeFile(paths.draftSchemaChange, schemaChange);
}

/** Writes draft/draft.json (creating the draft folder if needed). */
export async function writeDraftMetadata(
  paths: ProjectPaths,
  metadata: DraftMetadata,
): Promise<void> {
  await mkdir(paths.draft, { recursive: true });
  await writeFile(
    paths.draftMetadata,
    `${JSON.stringify({ name: metadata.name, desiredSchemaHash: metadata.desiredSchemaHash, recoveryOf: metadata.recoveryOf }, null, 2)}\n`,
  );
}

/** The command needs a draft and there is none. */
export class NoDraftError extends SuperDeployError {
  readonly code = "no-draft";

  constructor(action: string) {
    super(`There is no draft to ${action}; run draft first`);
  }
}

/** draft.json can't be read as a draft's metadata. */
export class InvalidDraftError extends SuperDeployError {
  readonly code = "invalid-draft";
  /** Project-relative path of draft.json. */
  readonly file: string;

  constructor(file: string, problem: string, options?: ErrorOptions) {
    super(`${file} ${problem}`, options);
    this.file = file;
  }
}

/** finalize found a file in the draft folder that a draft doesn't hold. */
export class UnknownDraftFileError extends SuperDeployError {
  readonly code = "unknown-draft-file";
  /** Project-relative path with forward slashes. */
  readonly file: string;

  constructor(unknown: UnknownDraftFile, finalizedAs: FinalizedFolderKind) {
    super(
      `${unknown.message}: a finalized ${finalizedAs} can't hold it, so rename it to one of those or move it out of the draft folder, then finalize again`,
    );
    this.file = unknown.file;
  }
}
