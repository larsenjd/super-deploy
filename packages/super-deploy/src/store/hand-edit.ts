// A schema change edited by hand (QA 108, 161). The schema change is
// generated and never meant to be edited, but the maintainer chose to make a
// hand edit visible rather than refuse it: `draft` keeps the schema change
// it generated beside the draft (generatedSchemaChangeFileName), and a draft
// whose schema-change.sql differs from that copy (line endings aside) was
// edited by hand.
//
// - `rehearse` and `finalize` warn about it; the rehearsal still proves the
//   result. `deploy-draft`, which doesn't rehearse, says so in its YES
//   confirmation and goes ahead on YES.
// - `finalize` records it in the migration's metadata.json
//   (`schemaChangeEditedByHand: true`) and writes HAND-EDITED.md into the
//   migration, with a unified diff from the generated schema change to the
//   finalized one. Both are hashed like every other file, so a reviewer sees
//   the edit in the pull request; `validate` lists such migrations as a
//   notice, which `--strict` doesn't fail on.
// - `unfinalize` restores the generated copy from that diff, so finalizing
//   again unchanged (with the same versions) reproduces the migration.
//
// A draft without the generated copy (written before it existed) counts as
// not edited. A Recovery draft never has one: its schema change is its
// migration's, with its own check (RecoverySchemaChangeEditedError).

import { join } from "node:path";
import { generatedSchemaChangeFileName } from "./draft.ts";
import { normaliseLineEndings } from "./hashing.ts";
import { type ProjectPaths, projectRelative } from "./layout.ts";
import {
  metadataFileName,
  readIfPresent,
  readNormalisedIfPresent,
  schemaChangeFileName,
} from "./migrations.ts";
import { unapplyUnifiedDiff, unifiedDiff } from "./unified-diff.ts";

/** The report finalize writes into a migration whose schema change was edited by hand. */
export const handEditReportFileName = "HAND-EDITED.md";

/**
 * Whether the finalized migration in folder `path` records a hand-edited
 * schema change (`schemaChangeEditedByHand` in its metadata.json). False
 * when metadata.json is missing or isn't JSON: integrity reports those.
 */
export async function migrationEditedByHand(path: string): Promise<boolean> {
  const text = await readIfPresent(join(path, metadataFileName));
  try {
    const metadata: unknown = text === undefined ? undefined : JSON.parse(text);
    return (
      typeof metadata === "object" &&
      metadata !== null &&
      "schemaChangeEditedByHand" in metadata &&
      metadata.schemaChangeEditedByHand === true
    );
  } catch {
    return false;
  }
}

/** A draft's schema change that differs from the one `draft` generated. */
export interface SchemaChangeHandEdit {
  /** Project-relative path of the draft's schema-change.sql. */
  readonly file: string;
  /** The schema change `draft` generated (LF line endings). */
  readonly generated: string;
  /** The schema change as edited (LF line endings). */
  readonly edited: string;
}

/**
 * The draft's hand edit of its schema change; undefined when it has none, or
 * either file is missing.
 */
export async function draftSchemaChangeHandEdit(
  root: string,
  paths: ProjectPaths,
): Promise<SchemaChangeHandEdit | undefined> {
  const generated = await readNormalisedIfPresent(
    join(paths.draft, generatedSchemaChangeFileName),
  );
  const edited = await readNormalisedIfPresent(paths.draftSchemaChange);
  if (generated === undefined || edited === undefined || generated === edited) {
    return undefined;
  }
  return {
    file: projectRelative(root, paths.draftSchemaChange),
    generated,
    edited,
  };
}

/** The warning about a hand edit of `file`, a draft's schema change. */
export function handEditWarning(file: string): string {
  return `${file} was edited by hand since draft generated it`;
}

const diffLabels = {
  from: `${schemaChangeFileName} (generated by draft)`,
  to: `${schemaChangeFileName} (finalized)`,
};

/** HAND-EDITED.md for a migration finalized with `edit`. */
export function handEditReport(edit: SchemaChangeHandEdit): string {
  return [
    "# Schema change edited by hand",
    "",
    `\`${schemaChangeFileName}\` was edited by hand after \`draft\` generated it.`,
    "The diff goes from the schema change `draft` generated to the one",
    "finalized. The rehearsal at finalize proved that the edited schema change",
    "produces the desired schema.",
    "",
    "```diff",
    `${unifiedDiff(edit.generated, edit.edited, diffLabels)}\`\`\``,
    "",
  ].join("\n");
}

/** The schema change `draft` generated, from a migration's HAND-EDITED.md and its schema change. */
export function generatedFromReport(
  report: string,
  schemaChange: string,
): string {
  const text = normaliseLineEndings(report);
  // Diff lines start with a space, +, -, @ or \, so none closes the fence.
  const start = text.indexOf("```diff\n") + "```diff\n".length;
  const diff = text.slice(start, text.indexOf("\n```", start) + 1);
  return unapplyUnifiedDiff(diff, normaliseLineEndings(schemaChange));
}
