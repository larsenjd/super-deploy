// The project directory layout (default folder `data-model/`):
//
//   <directory>/
//     desired-schema/            the desired schema: any *.sql files, any folders
//     draft/                     the one draft (absent when there is none)
//       draft.json               { "name": "<kebab-case name>", "desiredSchemaHash": "<hex>",
//                                  "schemaChangeHash": "<hex>" },
//                                or for a Recovery draft { "name": ..., "recoveryOf": N }
//       pre-migration.sql        optional, hand-written: runs before the schema change
//       schema-change.sql        generated by `draft`; never edited by hand
//       post-migration.sql       optional, hand-written: runs after it (data only)
//     migrations/                finalized migrations; layout in store/migrations.ts
//       index.json               the hash-chain index
//       <NNNNN>-<name>/          read-only, hashed
import { join, relative, sep } from "node:path";

export interface ProjectPaths {
  /** Absolute path of the project directory (`directory` in config). */
  readonly directory: string;
  readonly desiredSchema: string;
  readonly draft: string;
  readonly draftMetadata: string;
  readonly draftSchemaChange: string;
  readonly migrations: string;
}

export function projectPaths(root: string, directory: string): ProjectPaths {
  const base = join(root, directory);
  const draft = join(base, "draft");
  return {
    directory: base,
    desiredSchema: join(base, "desired-schema"),
    draft,
    draftMetadata: join(draft, "draft.json"),
    draftSchemaChange: join(draft, "schema-change.sql"),
    migrations: join(base, "migrations"),
  };
}

/** A path relative to the project root with forward slashes, as shown in messages. */
export function projectRelative(root: string, path: string): string {
  return relative(root, path).split(sep).join("/");
}
